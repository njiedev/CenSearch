// Turns the rows into one SVG path, merging each horizontal run into a rect.
export function pixelPath(rows: string[]) {
  let path = ''
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      if (row[x] !== '#') {
        x++
        continue
      }
      const start = x
      while (row[x] === '#') {
        x++
      }
      path += `M${start} ${y}h${x - start}v1h${start - x}z`
    }
  })
  return path
}
